"""策略：哪些文书**默认**要求回传核对。

## 为什么是「默认」而不是「一律」

核对要花 OCR 与人工时间。把全量文书都设成必核对，「待裁决清单」就变成
第二份收件箱——没人看得完的清单等于没有清单。所以只对「改一个字就得重跑」
的四类文书默认开：起诉状、授权委托书、送达地址确认书、退费账户确认书。

## 为什么用子串匹配

卷宗里的写法不统一（「民事起诉状（一审）」「起诉状_定稿_20261106」
「授权委托书（含送达地址）」）。要求精确相等，等于让策略在真实数据上
永远不命中——漏掉一次默认核对，律师第一次看到改动就是在开庭前。
反向风险（「起诉状副本」被命中）在这个方向上可接受：多核一次只是多花时间。
"""

from __future__ import annotations

#: 高风险四类。只写文书名主干，前后的卷宗写法差异交给子串匹配吃掉。
HIGH_RISK_DOC_TYPES: tuple[str, ...] = (
    "起诉状",
    "授权委托书",
    "送达地址确认书",
    "退费账户确认书",
)


def should_verify(doc_type: str) -> bool:
    """该文书名是否默认要求回传核对（首尾空白不算差异；空名字一律不要求）。"""
    name = (doc_type or "").strip()
    if not name:
        return False
    return any(marker in name for marker in HIGH_RISK_DOC_TYPES)
